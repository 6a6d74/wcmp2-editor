export function bboxToPolygon(bbox: BBox4): GeoJSON.Polygon {
  const [w, s, e, n] = bbox;
  return {
    type: 'Polygon',
    coordinates: [[[w, s], [e, s], [e, n], [w, n], [w, s]]],
  };
}

